import { readFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { spawnSync } from 'node:child_process';
const [candidate,gui]=process.argv.slice(2);
const state=JSON.parse(await readFile(join(gui,'viewer.json'),'utf8'));
const source=dirname(fileURLToPath(import.meta.url));
if(await readFile(join(gui,'account-free-fixture'),'utf8')!=='owned touch fixture\n')throw Error('Account-free fixture required');
const encoded=spawnSync(join(process.env.PREFIX,'bin/python3'),['-B','-c','import json,sys; from open_viewer import viewer_url; print(viewer_url(json.loads(sys.stdin.read())))'],{cwd:source,input:JSON.stringify(state),encoding:'utf8'});
if(encoded.status!==0)throw Error('URL builder refused state');
const {chromium}=await import(pathToFileURL(join(candidate,'node_modules/playwright-core/index.mjs')).href);
const executablePath=join(process.env.PREFIX,'lib/chromium/chrome');
const args=['--no-sandbox','--disable-dev-shm-usage','--window-position=0,0'];
const desktop=await chromium.launch({executablePath,headless:false,args});
let viewer;let remote;let stage='launch';
try{
 remote=await desktop.newPage({viewport:{width:520,height:600}});
 await remote.goto('data:text/html,<style>body{margin:0;background:white}input{width:100vw;height:80vh;font:24px sans-serif;border:0}</style><input id="owned" aria-label="Owned test input">');
 await remote.bringToFront();
 viewer=await chromium.launch({executablePath,headless:true,args});
 const page=await viewer.newPage({viewport:{width:360,height:740},isMobile:true,hasTouch:true});
 await page.goto(encoded.stdout.trim(),{waitUntil:'domcontentloaded',timeout:15000});
 stage='connect';
 await page.waitForFunction(()=>document.documentElement.classList.contains('noVNC_connected'),{},{timeout:15000});
 await page.waitForTimeout(750);
 const canvas=page.locator('#noVNC_container canvas');
 const before=await page.evaluate(()=>document.activeElement?.id==='noVNC_keyboardinput');
 if(before)throw Error('Keyboard focused without a gesture');
 const box=await canvas.boundingBox();
 await page.mouse.click(box.x+120,box.y+220);
 if(await page.evaluate(()=>document.activeElement?.id==='noVNC_keyboardinput'))throw Error('Mouse click opened mobile keyboard');
 const session=await page.context().newCDPSession(page);
 const point={x:box.x+120,y:box.y+220};
 await session.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[point]});
 await session.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{...point,y:point.y+45}]});
 await session.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 if(await page.evaluate(()=>document.activeElement?.id==='noVNC_keyboardinput'))throw Error('Scroll gesture opened mobile keyboard');
 await session.detach();
 await canvas.tap({position:{x:330,y:220}});
 const focused=await page.evaluate(()=>document.activeElement?.id==='noVNC_keyboardinput');
 if(!focused)throw Error('First trusted touch did not focus virtual keyboard');
 stage='first-input';
 await page.keyboard.type('owned-touch-731');
 await remote.waitForFunction(()=>document.querySelector('#owned').value==='owned-touch-731',{},{timeout:5000});
 stage='first-focus-retention';
 await page.waitForTimeout(2300);
 if(!await page.evaluate(()=>document.activeElement?.id==='noVNC_keyboardinput'))throw Error('Initial delayed controlbar stole keyboard focus');
 const input=page.locator('#noVNC_keyboardinput');
 await input.evaluate(element=>{window.ownedFocusCount=0;element.addEventListener('focus',()=>window.ownedFocusCount++);element.blur();});
 await canvas.tap({position:{x:330,y:220}});
 if(!await page.evaluate(()=>document.activeElement?.id==='noVNC_keyboardinput'))throw Error('Repeat touch after blur did not focus keyboard');
 stage='second-input';
 // Closely spaced remote taps may select a word; append through the real End key.
 await page.keyboard.press('End');
 await page.keyboard.type('-second');
 await remote.waitForFunction(()=>document.querySelector('#owned').value==='owned-touch-731-second',{},{timeout:5000});
 const firstCount=await page.evaluate(()=>window.ownedFocusCount);
 await canvas.tap({position:{x:330,y:220}});
 const refreshed=await page.evaluate(()=>document.activeElement?.id==='noVNC_keyboardinput'&&window.ownedFocusCount>0);
 const nextCount=await page.evaluate(()=>window.ownedFocusCount);
 if(!refreshed||nextCount<=firstCount)throw Error('Repeat touch did not refresh stale DOM focus');
 stage='third-input';
 await page.keyboard.press('End');
 await page.keyboard.type('-third');
 await remote.waitForFunction(()=>document.querySelector('#owned').value==='owned-touch-731-second-third',{},{timeout:5000});
 const automatic=page.locator('#owned_keyboard_auto');
 const manualButton=page.locator('#owned_keyboard');
 stage='independent-controls';
 await manualButton.tap();
 if(await page.evaluate(()=>document.activeElement?.id==='noVNC_keyboardinput')||await automatic.getAttribute('aria-checked')!=='true')throw Error('Manual close changed automatic setting or failed to close');
 await canvas.tap({position:{x:330,y:220}});
 if(!await page.evaluate(()=>document.activeElement?.id==='noVNC_keyboardinput'))throw Error('Automatic mode failed after manual close');
 await automatic.tap();
 if(await automatic.getAttribute('aria-checked')!=='false'||!await page.evaluate(()=>document.activeElement?.id==='noVNC_keyboardinput'))throw Error('Automatic preference changed manual visibility');
 await manualButton.tap();
 await canvas.tap({position:{x:330,y:220}});
 if(await page.evaluate(()=>document.activeElement?.id==='noVNC_keyboardinput'))throw Error('Disabled automatic mode reopened keyboard');
 await manualButton.tap();
 if(!await page.evaluate(()=>document.activeElement?.id==='noVNC_keyboardinput')||await automatic.getAttribute('aria-checked')!=='false')throw Error('Manual open changed automatic setting or failed to open');
 await automatic.tap();
 if(!await page.evaluate(()=>document.activeElement?.id==='noVNC_keyboardinput'))throw Error('Automatic preference stole keyboard focus');
 await manualButton.tap();
 const footer=await page.locator('#owned_mobile_controls').boundingBox();
 if(!footer||footer.height>44||footer.width>360||Math.abs(footer.y+footer.height-740)>1)throw Error('Compact mobile toolbar layout failed');
 for(const id of ['owned_keyboard','owned_keyboard_auto','owned_fullscreen']){
  const box=await page.locator('#'+id).boundingBox();
  if(!box||box.x<0||box.x+box.width>360||box.y<footer.y||box.y+box.height>footer.y+footer.height)throw Error('Toolbar control overflowed viewport');
 }
 const toolbarImage=join(gui,'toolbar.png');
 // The fixture is account-free. Capture only this owned toolbar, never login UI.
 await page.screenshot({path:toolbarImage,clip:{x:0,y:footer.y,width:360,height:footer.height}});
 console.log(JSON.stringify({mouseAndScrollDoNotOpen:true,initialDelayedFocusPreserved:true,repeatAfterBlur:true,staleFocusRefreshed:true,threeRealRfbInputReadbacks:true,manualAndAutomaticIndependent:true,autoOffPreserved:true,toolbarHeight:footer.height,toolbarImage}));
}catch(error){
 const fixture=remote?await remote.evaluate(()=>{const input=document.querySelector('#owned');return {focused:document.activeElement===input,length:input?.value.length,prefix:input?.value.startsWith('owned-touch-731'),second:input?.value.includes('-second'),third:input?.value.includes('-third')};}).catch(()=>null):null;
 console.log(JSON.stringify({failedStage:stage,fixture}));throw error;
}finally{await viewer?.close();await desktop.close();}
